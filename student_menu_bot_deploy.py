def build_top_keyboard() -> ReplyKeyboardMarkup:
    """បង្កើត Keyboard ថ្នាក់ដំបូង៖ ប្រភេទធំទាំង 6 ជា 2 ជួរឈរ"""
    keyboard = [
        [KeyboardButton(CATEGORY_ORDER[i]), *(
            [KeyboardButton(CATEGORY_ORDER[i + 1])] if i + 1 < len(CATEGORY_ORDER) else []
        )]
        for i in range(0, len(CATEGORY_ORDER), 2)
    ]
    return ReplyKeyboardMarkup(keyboard, resize_keyboard=True)


def build_sub_keyboard(category: str) -> ReplyKeyboardMarkup:
    """បង្កើត Keyboard Submenu៖ ចំណុចរងក្នុងប្រភេទដែលបានជ្រើស ជា 2 ជួរឈរ
    ព្រមទាំងប៊ូតុង 'ត្រឡប់ក្រោយ' នៅជួរចុងក្រោយ"""
    sub_labels = list(MENU_STRUCTURE[category].keys())
    keyboard = [
        [KeyboardButton(sub_labels[i]), *(
            [KeyboardButton(sub_labels[i + 1])] if i + 1 < len(sub_labels) else []
        )]
        for i in range(0, len(sub_labels), 2)
    ]
    keyboard.append([KeyboardButton(BACK_LABEL)])
    return ReplyKeyboardMarkup(keyboard, resize_keyboard=True)


async def start(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """ពេលអ្នកប្រើវាយ /start ឬ /menu — កំណត់ត្រឡប់ទៅ Menu ដើម ហើយបង្ហាញភ្លាមៗ"""
    context.user_data["current_category"] = None
    await update.message.reply_text(
        WELCOME_MESSAGE,
        reply_markup=build_top_keyboard(),
    )


async def handle_text(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """ដោះស្រាយសារគ្រប់សារ អាស្រ័យលើថាតើអ្នកប្រើកំពុងនៅ Menu ដើម ឬក្នុង Submenu៖
    - Menu ដើម + ចុចប្រភេទធំ → ចូល Submenu
    - Submenu + ចុច 'ត្រឡប់ក្រោយ' → ត្រឡប់ទៅ Menu ដើម
    - Submenu + ចុចចំណុចរង → បង្ហាញចម្លើយ ហើយនៅតែក្នុង Submenu ដដែល
    - អត្ថបទមិនត្រូវនឹងអ្វីទាំងអស់ → សារ Fallback
    """
    text = update.message.text.strip()
    current_category = context.user_data.get("current_category")

    # ករណីទី 1៖ កំពុងនៅ Menu ដើម (មិនទាន់ចូល Category ណាមួយ)
    if current_category is None:
        if text in MENU_STRUCTURE:
            context.user_data["current_category"] = text
            await update.message.reply_text(
                f"អ្នកកំពុងនៅក្នុង *{text}*\nសូមជ្រើសរើសចំណុចរងខាងក្រោម៖",
                parse_mode="Markdown",
                reply_markup=build_sub_keyboard(text),
            )
        else:
            await update.message.reply_text(
                FALLBACK_MESSAGE,
                parse_mode="Markdown",
                link_preview_options=LinkPreviewOptions(is_disabled=True),
                reply_markup=build_top_keyboard(),
            )
        return

    # ករណីទី 2៖ កំពុងនៅក្នុង Submenu របស់ Category មួយ
    if text == BACK_LABEL:
        context.user_data["current_category"] = None
        await update.message.reply_text(
            WELCOME_MESSAGE,
            reply_markup=build_top_keyboard(),
        )
        return

    answer = MENU_STRUCTURE.get(current_category, {}).get(text)
    if answer:
        await update.message.reply_text(
            answer,
            parse_mode="Markdown",
            link_preview_options=LinkPreviewOptions(is_disabled=True),
            reply_markup=build_sub_keyboard(current_category),
        )
    else:
        await update.message.reply_text(
            FALLBACK_MESSAGE,
            parse_mode="Markdown",
            link_preview_options=LinkPreviewOptions(is_disabled=True),
            reply_markup=build_sub_keyboard(current_category),
        )


